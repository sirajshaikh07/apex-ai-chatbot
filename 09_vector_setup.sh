#!/usr/bin/env bash
set -euo pipefail

echo "=========================================================="
echo "  Phase 9: Vector Search, Ingestion & In-DB Embeddings"
echo "=========================================================="

source /home/ubuntu/project/values.env
source /home/ubuntu/.secrets.env

SQLCL="/usr/local/bin/sql -thin -S /nolog"

echo ""
echo "[1] Creating ONNX_DIR directory as SYSDBA on VM1..."
${SQLCL} <<EOF
connect sys/"${SYS_PWD}"@//${VM1_IP}:${DB_PORT}/${DB_SERVICE} as sysdba
set serveroutput on heading on feedback off linesize 200

CREATE OR REPLACE DIRECTORY ONNX_DIR AS '/opt/oracle/onnx';
GRANT READ, WRITE ON DIRECTORY ONNX_DIR TO AIDEMO;

PROMPT Directory ONNX_DIR verified and granted to AIDEMO.
exit;
EOF

echo ""
echo "[2] Verifying ONNX embedding model in AIDEMO schema..."
/usr/local/bin/sql -thin AIDEMO/"${AIDEMO_PWD}"@//${VM1_IP}:${DB_PORT}/${DB_SERVICE} <<EOF
set heading on feedback off linesize 200

PROMPT === USER_MINING_MODELS Status ===
SELECT model_name, mining_function, algorithm FROM user_mining_models WHERE model_name = 'ALL_MINILM_L12_V2';

PROMPT === Testing Vector Embedding Dimension ===
SELECT vector_dimension(vector_embedding(ALL_MINILM_L12_V2 USING 'Hello Oracle AI 26ai' AS data)) AS embedding_dimensions FROM dual;
exit;
EOF

echo ""
echo "[3] Creating SOURCE_DOCS and DOC_CHUNKS tables..."
${SQLCL} <<EOF
connect AIDEMO/"${AIDEMO_PWD}"@//${VM1_IP}:${DB_PORT}/${DB_SERVICE}
set serveroutput on heading on feedback off linesize 200

-- SOURCE_DOCS Table
DECLARE
  v_count NUMBER;
BEGIN
  SELECT count(*) INTO v_count FROM user_tables WHERE table_name = 'SOURCE_DOCS';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE '
      CREATE TABLE source_docs (
        doc_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        title       VARCHAR2(255) NOT NULL UNIQUE,
        source_ref  VARCHAR2(255),
        content     CLOB,
        ingested_at TIMESTAMP
      )';
    dbms_output.put_line('Table SOURCE_DOCS created.');
  ELSE
    dbms_output.put_line('Table SOURCE_DOCS already exists.');
  END IF;
END;
/

-- DOC_CHUNKS Table with VECTOR(384, FLOAT32)
DECLARE
  v_count NUMBER;
BEGIN
  SELECT count(*) INTO v_count FROM user_tables WHERE table_name = 'DOC_CHUNKS';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE '
      CREATE TABLE doc_chunks (
        chunk_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        doc_id     NUMBER REFERENCES source_docs(doc_id) ON DELETE CASCADE,
        chunk_no   NUMBER,
        chunk_text CLOB,
        embedding  VECTOR(384, FLOAT32)
      )';
    dbms_output.put_line('Table DOC_CHUNKS with VECTOR(384, FLOAT32) created.');
  ELSE
    dbms_output.put_line('Table DOC_CHUNKS already exists.');
  END IF;
END;
/
exit;
EOF

echo ""
echo "[4] Loading Enterprise Policy Documents into SOURCE_DOCS..."
/usr/local/bin/sql -thin AIDEMO/"${AIDEMO_PWD}"@//${VM1_IP}:${DB_PORT}/${DB_SERVICE} @/home/ubuntu/docs/load_corpus.sql

echo ""
echo "[5] Ingesting documents: Vector Chunking & In-DB Embeddings..."
/usr/local/bin/sql -thin AIDEMO/"${AIDEMO_PWD}"@//${VM1_IP}:${DB_PORT}/${DB_SERVICE} <<EOF
set serveroutput on heading on feedback on linesize 200

-- Ingest chunks and embeddings using native VECTOR_CHUNKS and VECTOR_EMBEDDING
INSERT INTO doc_chunks (doc_id, chunk_no, chunk_text, embedding)
SELECT d.doc_id, 
       ROW_NUMBER() OVER (PARTITION BY d.doc_id ORDER BY c.chunk_offset),
       c.chunk_text,
       VECTOR_EMBEDDING(ALL_MINILM_L12_V2 USING c.chunk_text AS data)
FROM   source_docs d,
       VECTOR_CHUNKS(d.content BY words MAX 150 OVERLAP 15
                     SPLIT BY recursively LANGUAGE american NORMALIZE all) c
WHERE  d.ingested_at IS NULL;

UPDATE source_docs SET ingested_at = SYSTIMESTAMP WHERE ingested_at IS NULL;
COMMIT;

PROMPT === Ingestion Summary ===
SELECT d.title, count(c.chunk_id) as total_chunks
FROM source_docs d
LEFT JOIN doc_chunks c ON d.doc_id = c.doc_id
GROUP BY d.title;
exit;
EOF

echo ""
echo "[6] Creating SEARCH_CHUNKS semantic similarity search function..."
${SQLCL} <<EOF
connect AIDEMO/"${AIDEMO_PWD}"@//${VM1_IP}:${DB_PORT}/${DB_SERVICE}
set serveroutput on heading on feedback off linesize 200

CREATE OR REPLACE FUNCTION search_chunks (
  p_question VARCHAR2,
  p_k        NUMBER DEFAULT 3
) RETURN SYS_REFCURSOR IS
  c SYS_REFCURSOR;
BEGIN
  OPEN c FOR
    SELECT d.doc_id,
           d.title,
           c.chunk_no,
           ROUND(VECTOR_DISTANCE(c.embedding, VECTOR_EMBEDDING(ALL_MINILM_L12_V2 USING p_question AS data), COSINE), 4) as distance,
           c.chunk_text
    FROM   source_docs d
    JOIN   doc_chunks c ON d.doc_id = c.doc_id
    ORDER BY VECTOR_DISTANCE(c.embedding, VECTOR_EMBEDDING(ALL_MINILM_L12_V2 USING p_question AS data), COSINE)
    FETCH FIRST p_k ROWS ONLY;
  RETURN c;
END;
/
PROMPT Function SEARCH_CHUNKS created successfully.
exit;
EOF

echo ""
echo "[7] Running 5-Question Enterprise Retrieval Test Suite..."
python3 - << 'PYEOF'
import subprocess, os

values = {}
with open("/home/ubuntu/project/values.env") as f:
    for line in f:
        if "=" in line and not line.startswith("#"):
            k, v = line.strip().split("=", 1)
            values[k] = v

secrets = {}
with open("/home/ubuntu/.secrets.env") as f:
    for line in f:
        if "=" in line and not line.startswith("#"):
            k, v = line.strip().split("=", 1)
            secrets[k] = v

vm1_ip = values.get("VM1_IP", "20.0.1.130")
db_port = values.get("DB_PORT", "1521")
db_service = values.get("DB_SERVICE", "FREEPDB1")
aidemo_pwd = secrets.get("AIDEMO_PWD", "Apex_26ai_2026Free")

passed = 0
total = 0

with open("/home/ubuntu/docs/test_questions.csv") as f:
    for line in f:
        line = line.strip()
        if not line or ";" not in line: continue
        total += 1
        q, expected_doc = line.split(";", 1)
        
        q_escaped = q.replace("'", "''")
        sql = f"""
connect AIDEMO/{aidemo_pwd}@//{vm1_ip}:{db_port}/{db_service}
set heading off feedback off linesize 200 pagesize 10
SELECT d.title, ROUND(VECTOR_DISTANCE(c.embedding, VECTOR_EMBEDDING(ALL_MINILM_L12_V2 USING '{q_escaped}' AS data), COSINE), 4) as dist
FROM source_docs d JOIN doc_chunks c ON d.doc_id = c.doc_id
ORDER BY dist ASC FETCH FIRST 3 ROWS ONLY;
exit;
"""
        res = subprocess.run(["/usr/local/bin/sql", "-thin", "-S", "/nolog"], input=sql, text=True, capture_output=True)
        top_matches = [l.strip().split()[0] for l in res.stdout.strip().splitlines() if l.strip() and not l.startswith("Connected")]
        is_match = expected_doc.strip() in top_matches
        if is_match: passed += 1
        print(f"Q{total}: '{q[:45]}...'")
        print(f"   Expected: {expected_doc.strip()} | Top matches: {top_matches} -> {'PASS' if is_match else 'FAIL'}")

print(f"\nFinal Retrieval Score: {passed}/{total} Passed (Required: >= 4/5)")
PYEOF

echo ""
echo "=== Phase 9 Vectors & RAG Ingestion Complete! ==="
