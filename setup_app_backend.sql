DECLARE
  v_count NUMBER;
BEGIN
  SELECT count(*) INTO v_count FROM user_tables WHERE table_name = 'CHAT_HISTORY';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE '
      CREATE TABLE chat_history (
        msg_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        session_id   NUMBER,
        user_name    VARCHAR2(100),
        user_prompt  VARCHAR2(4000),
        ai_response  CLOB,
        sources      VARCHAR2(1000),
        created_at   TIMESTAMP DEFAULT SYSTIMESTAMP
      )';
    dbms_output.put_line('Table CHAT_HISTORY created.');
  ELSE
    dbms_output.put_line('Table CHAT_HISTORY already exists.');
  END IF;
END;
