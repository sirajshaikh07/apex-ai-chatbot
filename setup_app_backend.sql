PROMPT === 3. Creating INGEST_DOCUMENT Auto-Vectorization Procedure ===
CREATE OR REPLACE PROCEDURE ingest_document (
  p_title        IN  VARCHAR2,
  p_ref          IN  VARCHAR2,
  p_content      IN  CLOB,
  p_chunks_count OUT NUMBER
) AS
  v_doc_id NUMBER;
BEGIN
  -- Insert or update document in SOURCE_DOCS
  MERGE INTO source_docs d
  USING (SELECT p_title AS title, NVL(p_ref, p_title) AS source_ref, p_content AS content FROM dual) s
  ON (d.title = s.title)
  WHEN MATCHED THEN
    UPDATE SET content = s.content, source_ref = s.source_ref, ingested_at = NULL
  WHEN NOT MATCHED THEN
    INSERT (title, source_ref, content) VALUES (s.title, s.source_ref, s.content);
  
  SELECT doc_id INTO v_doc_id FROM source_docs WHERE title = p_title;

  -- Delete previous chunks if document was updated
  DELETE FROM doc_chunks WHERE doc_id = v_doc_id;

  -- Ingest chunks and embeddings in real-time
  INSERT INTO doc_chunks (doc_id, chunk_no, chunk_text, embedding)
  SELECT d.doc_id, 
         ROW_NUMBER() OVER (PARTITION BY d.doc_id ORDER BY c.chunk_offset),
         c.chunk_text,
         VECTOR_EMBEDDING(ALL_MINILM_L12_V2 USING c.chunk_text AS data)
  FROM   source_docs d,
         VECTOR_CHUNKS(d.content BY words MAX 150 OVERLAP 15
                       SPLIT BY recursively LANGUAGE american NORMALIZE all) c
  WHERE  d.doc_id = v_doc_id;

  SELECT count(*) INTO p_chunks_count FROM doc_chunks WHERE doc_id = v_doc_id;

  UPDATE source_docs SET ingested_at = SYSTIMESTAMP WHERE doc_id = v_doc_id;
  COMMIT;
END ingest_document;
/

PROMPT Procedure INGEST_DOCUMENT created successfully.
exit;
