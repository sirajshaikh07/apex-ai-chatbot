-- 1. Create ENTERPRISE_PROJECTS Table
DECLARE
  v_exists NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_exists FROM user_tables WHERE table_name = 'ENTERPRISE_PROJECTS';
  IF v_exists = 0 THEN
    EXECUTE IMMEDIATE '
      CREATE TABLE enterprise_projects (
        project_id       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
        project_code     VARCHAR2(50) NOT NULL UNIQUE,
        project_name     VARCHAR2(255) NOT NULL,
        owner_name       VARCHAR2(100),
        manager_name     VARCHAR2(100),
        status           VARCHAR2(50) DEFAULT ''Active'',
        total_items      NUMBER DEFAULT 0,
        done_items       NUMBER DEFAULT 0,
        open_items       NUMBER DEFAULT 0,
        overdue_items    NUMBER DEFAULT 0,
        blocked_items    NUMBER DEFAULT 0,
        completion_pct   NUMBER DEFAULT 0,
        description      VARCHAR2(4000),
        source_doc_id    NUMBER,
        created_at       TIMESTAMP(6) DEFAULT SYSTIMESTAMP,
        updated_at       TIMESTAMP(6) DEFAULT SYSTIMESTAMP
      )';
    DBMS_OUTPUT.PUT_LINE('Created table ENTERPRISE_PROJECTS');
  ELSE
    DBMS_OUTPUT.PUT_LINE('Table ENTERPRISE_PROJECTS already exists');
  END IF;
END;
/

